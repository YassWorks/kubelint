//! Developer automation for kubelint, run with `cargo xtask <task>`.
//!
//! Tasks write files into the repository. A test checks that their committed output is
//! up to date, so CI fails when someone forgets to run one.

use std::path::{Path, PathBuf};

use kubelint_linter::rules;

/// Two levels above this crate's manifest.
pub fn repository_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

const RULE_DOCS: &str = "docs/rules";

/// Each rule's page, as a path relative to the repository root and its content.
pub fn rule_pages() -> Vec<(PathBuf, String)> {
    rules::ALL
        .iter()
        .map(|rule| {
            let meta = rule.meta();
            let content = format!(
                "<!-- Generated by `cargo xtask gen-rule-docs` from the rule's source. Do not edit. -->\n\n{}",
                meta.documentation()
            );
            (Path::new(RULE_DOCS).join(format!("{}.md", meta.code)), content)
        })
        .collect()
}

/// The `KL*.md` pages in `docs/rules/` that no rule produces, relative to the
/// repository root.
pub fn orphan_rule_pages() -> std::io::Result<Vec<PathBuf>> {
    let pages: Vec<PathBuf> = rule_pages().into_iter().map(|(path, _)| path).collect();
    let mut orphans = Vec::new();
    for entry in std::fs::read_dir(repository_root().join(RULE_DOCS))? {
        let name = entry?.file_name();
        let path = Path::new(RULE_DOCS).join(&name);
        let name = name.to_string_lossy();
        if name.starts_with("KL") && name.ends_with(".md") && !pages.contains(&path) {
            orphans.push(path);
        }
    }
    Ok(orphans)
}
